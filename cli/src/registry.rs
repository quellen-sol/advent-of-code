//! Rust and Go can't load a day by name at runtime, so each gets a generated
//! dispatch table built from the solution files on disk. TypeScript and Python
//! load days dynamically and need nothing here.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
    fs,
    path::Path,
};

use anyhow::{Context, Result};

use crate::lang::Lang;

type Index = BTreeMap<u16, BTreeSet<u8>>;

const RUST_HEADER: &str = "// @generated by `aoc`. Manual edits are overwritten.";
const GO_HEADER: &str = "// Code generated by aoc; DO NOT EDIT.";

pub fn sync(root: &Path, lang: Lang) -> Result<()> {
    match lang {
        Lang::Rust => sync_rust(&root.join("rust/src/years")),
        Lang::Go => sync_go(&root.join("go/years")),
        Lang::TypeScript | Lang::Python => Ok(()),
    }
}

fn sync_rust(years_dir: &Path) -> Result<()> {
    let index = scan(years_dir, "solutions", ".rs")?;

    for (year, days) in &index {
        let year_dir = years_dir.join(format!("y{year}"));
        write_if_changed(&year_dir.join("mod.rs"), "pub mod solutions;\n")?;
        write_if_changed(
            &year_dir.join("solutions/mod.rs"),
            &render_rust_solutions(days),
        )?;
    }

    write_if_changed(&years_dir.join("mod.rs"), &render_rust_years(&index))?;
    Ok(())
}

fn sync_go(years_dir: &Path) -> Result<()> {
    let index = scan(years_dir, "", ".go")?;
    write_if_changed(&years_dir.join("registry.go"), &render_go(&index))?;
    Ok(())
}

/// Finds `y{year}/{subdir}/day_{day}{extension}` files. Years without any days
/// are left out, so emptying a year can't leave a dangling reference to it.
fn scan(years_dir: &Path, subdir: &str, extension: &str) -> Result<Index> {
    let mut index = Index::new();
    let entries = fs::read_dir(years_dir)
        .with_context(|| format!("couldn't read {}", years_dir.display()))?;

    for entry in entries {
        let entry = entry?;
        let name = entry.file_name();
        let Some(year) = name.to_str().and_then(parse_year) else {
            continue;
        };
        let Ok(files) = fs::read_dir(entry.path().join(subdir)) else {
            continue;
        };

        let days: BTreeSet<u8> = files
            .flatten()
            .filter_map(|file| parse_day(file.file_name().to_str()?, extension))
            .collect();
        if !days.is_empty() {
            index.insert(year, days);
        }
    }

    Ok(index)
}

fn parse_year(dir_name: &str) -> Option<u16> {
    dir_name.strip_prefix('y')?.parse().ok()
}

/// Also rejects non-solutions like `day_1_test.go`, whose middle isn't a number.
fn parse_day(file_name: &str, extension: &str) -> Option<u8> {
    file_name
        .strip_prefix("day_")?
        .strip_suffix(extension)?
        .parse()
        .ok()
}

/// Skips the write when nothing changed, so the file's mtime doesn't trigger a
/// rebuild on every run. Returns whether it wrote.
fn write_if_changed(path: &Path, contents: &str) -> Result<bool> {
    if fs::read_to_string(path).is_ok_and(|current| current == contents) {
        return Ok(false);
    }
    fs::write(path, contents).with_context(|| format!("couldn't write {}", path.display()))?;
    Ok(true)
}

fn render_rust_solutions(days: &BTreeSet<u8>) -> String {
    // Lexicographic (`day_10` before `day_2`) because that's the order rustfmt
    // enforces on `mod` items. Anything else would flip back and forth between
    // `cargo fmt` and this generator.
    let mut modules: Vec<String> = days.iter().map(|day| format!("day_{day}")).collect();
    modules.sort();

    let mut out = format!("{RUST_HEADER}\n#![allow(unused)]\n\n");
    for module in modules {
        writeln!(out, "pub mod {module};").unwrap();
    }
    out
}

fn render_rust_years(index: &Index) -> String {
    let mut out =
        format!("{RUST_HEADER}\nuse std::time::Duration;\n\nuse crate::defs::Solution;\n\n");
    for year in index.keys() {
        writeln!(out, "pub mod y{year};").unwrap();
    }

    out.push_str(
        "\n/// Runs one day's solution, returning false if it doesn't exist.\n\
         #[rustfmt::skip]\n\
         pub fn run(year: u16, day: u8, input_path: &str, budget: Duration) -> bool {\n    \
             match (year, day) {\n",
    );
    for (year, days) in index {
        for day in days {
            writeln!(
                out,
                "        ({year}, {day}) => y{year}::solutions::day_{day}::Day{day}Solution::run_both_solutions(input_path, budget),"
            )
            .unwrap();
        }
    }
    out.push_str("        _ => return false,\n    }\n    true\n}\n");
    out
}

fn render_go(index: &Index) -> String {
    let mut out = format!("{GO_HEADER}\n\npackage years\n\n");

    // Go refuses to compile unused imports, so an empty registry only has the
    // one that `Run`'s signature needs.
    out.push_str("import (\n");
    if !index.is_empty() {
        out.push_str("\t\"advent/adventlib\"\n");
        for year in index.keys() {
            writeln!(out, "\t\"advent/years/y{year}\"").unwrap();
        }
    }
    out.push_str("\t\"time\"\n)\n\n");

    out.push_str(
        "// Run runs one day's solution, returning false if it doesn't exist.\n\
         func Run(year int, day int, inputPath string, budget time.Duration) bool {\n\
         \tswitch [2]int{year, day} {\n",
    );
    for (year, days) in index {
        for day in days {
            writeln!(
                out,
                "\tcase [2]int{{{year}, {day}}}:\n\t\tadventlib.RunSolution(func() *y{year}.Day{day}Solution {{ return &y{year}.Day{day}Solution{{}} }}, inputPath, budget)"
            )
            .unwrap();
        }
    }
    out.push_str("\tdefault:\n\t\treturn false\n\t}\n\treturn true\n}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn index(entries: &[(u16, &[u8])]) -> Index {
        entries
            .iter()
            .map(|(year, days)| (*year, days.iter().copied().collect()))
            .collect()
    }

    fn touch(path: &Path) {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, "").unwrap();
    }

    #[test]
    fn rust_dispatch_is_numeric_but_mods_follow_rustfmt() {
        let index = index(&[(2024, &[2, 10])]);

        let years = render_rust_years(&index);
        let day_2 = years.find("(2024, 2) =>").unwrap();
        let day_10 = years.find("(2024, 10) =>").unwrap();
        assert!(day_2 < day_10);

        let solutions = render_rust_solutions(&index[&2024]);
        let day_2 = solutions.find("pub mod day_2;").unwrap();
        let day_10 = solutions.find("pub mod day_10;").unwrap();
        assert!(day_10 < day_2);
    }

    #[test]
    fn go_dispatch_covers_every_day() {
        let rendered = render_go(&index(&[(2025, &[1, 3])]));
        assert!(rendered.contains("\"advent/years/y2025\""));
        assert!(rendered.contains("case [2]int{2025, 3}:"));
        assert!(rendered.contains("return &y2025.Day3Solution{} }, inputPath, budget)"));
    }

    #[test]
    fn empty_go_registry_has_no_unused_imports() {
        let rendered = render_go(&Index::new());
        assert!(!rendered.contains("adventlib"));
        assert!(rendered.contains("budget time.Duration"));
    }

    #[test]
    fn scan_only_finds_real_solutions() {
        let dir = tempfile::tempdir().unwrap();
        for file in ["day_1.go", "day_1_test.go", "day_3.go", "helpers.go"] {
            touch(&dir.path().join("y2025").join(file));
        }
        touch(&dir.path().join("registry.go"));
        fs::create_dir(dir.path().join("y2026")).unwrap();

        assert_eq!(
            scan(dir.path(), "", ".go").unwrap(),
            index(&[(2025, &[1, 3])])
        );
    }

    #[test]
    fn sync_is_idempotent_and_tracks_deletions() {
        let dir = tempfile::tempdir().unwrap();
        let day_1 = dir.path().join("y2025/solutions/day_1.rs");
        let day_2 = dir.path().join("y2025/solutions/day_2.rs");
        touch(&day_1);
        touch(&day_2);

        sync_rust(dir.path()).unwrap();
        let years_file = dir.path().join("mod.rs");
        let first = fs::read_to_string(&years_file).unwrap();
        assert!(first.contains("Day2Solution"));

        let contents = render_rust_years(&scan(dir.path(), "solutions", ".rs").unwrap());
        assert!(!write_if_changed(&years_file, &contents).unwrap());

        fs::remove_file(&day_2).unwrap();
        sync_rust(dir.path()).unwrap();
        assert!(!fs::read_to_string(&years_file).unwrap().contains("Day2Solution"));
    }
}
